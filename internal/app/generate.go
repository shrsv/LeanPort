func generatePackage(e *env, bindings []Binding, archives []string, goos, goarch, mode string) error {
	pkg := bindings[0].Package
	dir := filepath.Join(e.root, e.cfg.Project.PackageDir, pkg)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	// Types file: one constant block per action table.
	var types strings.Builder
	types.WriteString("// Code generated by leanport. DO NOT EDIT.\n")
	fmt.Fprintf(&types, "package %s\n", pkg)
	seenEnum := map[string]bool{}
	for _, b := range bindings {
		if len(b.Actions) == 0 {
			continue
		}
		enumName := enumNameFor(b)
		if enumName == "" || seenEnum[enumName] {
			continue
		}
		seenEnum[enumName] = true
		fmt.Fprintf(&types, "\ntype %s uint8\n\nconst (\n", enumName)
		type kv struct {
			k string
			v uint8
		}
		var items []kv
		for k, v := range b.Actions {
			items = append(items, kv{k, v})
		}
		sort.Slice(items, func(i, j int) bool {
			if items[i].v != items[j].v {
				return items[i].v < items[j].v
			}
			return items[i].k < items[j].k
		})
		for _, it := range items {
			fmt.Fprintf(&types, "\t%s %s = %d\n", it.k, enumName, it.v)
		}
		types.WriteString(")\n")
	}
	if err := writeGoFile(filepath.Join(dir, pkg+".go"), types.String()); err != nil {
		return err
	}

	var cgo strings.Builder
	cgo.WriteString("// Code generated by leanport. DO NOT EDIT.\n")
	fmt.Fprintf(&cgo, "package %s\n\n/*\n", pkg)
	fmt.Fprintf(&cgo, "#cgo LDFLAGS: ")
	var ldflags []string
	for _, a := range archives {
		ldflags = append(ldflags, "${SRCDIR}/"+strings.TrimPrefix(filepath.ToSlash(a), e.cfg.Project.PackageDir+"/"+pkg+"/"))
	}
	ldflags = append(ldflags, "-lm", "-lpthread", "-ldl", "-lrt")
	cgo.WriteString(strings.Join(ldflags, " "))
	cgo.WriteString("\n")
	cgo.WriteString("#include <stdint.h>\n#include <stddef.h>\n#include <stdlib.h>\n\n")

	needsUnsafe := false
	for _, b := range bindings {
		args, _ := parseTypes(b.Args)
		res, _ := parseType(b.Result)
		for _, t := range append(append([]Type{}, args...), res) {
			if t.Kind == KindString || t.Kind == KindBytes {
				needsUnsafe = true
			}
		}
		cgo.WriteString(cPrototype(b, args, res))
		cgo.WriteString("\n")
	}
	cgo.WriteString("*/\nimport \"C\"\n")
	if needsUnsafe {
		cgo.WriteString("import \"unsafe\"\n")
	}
	cgo.WriteString("\n")

	needsB2U := false
	for _, b := range bindings {
		args, _ := parseTypes(b.Args)
		for _, t := range args {
			if t.Kind == KindBool {
				needsB2U = true
			}
		}
	}
	for _, b := range bindings {
		writeGoFunc(&cgo, b)
	}
	if needsB2U {
		cgo.WriteString("\nfunc b2u(b bool) C.uint8_t {\n\tif b {\n\t\treturn 1\n\t}\n\treturn 0\n}\n")
	}
	if err := writeGoFile(filepath.Join(dir, pkg+"_cgo.go"), cgo.String()); err != nil {
		return err
	}

	digest, err := writeManifest(e, pkg, bindings, archives, goos, goarch, mode)
	if err != nil {
		return err
	}
	// Make the Go package depend on the archive bytes: Go's build cache does
	// not always notice an archive rebuilt in place at the same path.
	stamp := fmt.Sprintf("// Code generated by leanport. DO NOT EDIT.\npackage %s\n\nconst artifactDigest = %q\n", pkg, digest)
	return writeGoFile(filepath.Join(dir, "artifact.go"), stamp)
}

func enumNameFor(b Binding) string {
	for _, a := range b.Args {
		if t, err := parseType(a); err == nil && t.Kind == KindEnum {
			return t.Enum
		}
	}
	if b.Result != "" {
		if t, err := parseType(b.Result); err == nil && t.Kind == KindEnum {
			return t.Enum
		}
	}
	return ""
}

func cPrototype(b Binding, args []Type, result Type) string {
	out := fmt.Sprintf("%s lp_go_%s(%s);", publicCType(result), b.GoName, publicCParams(args, result))
	switch result.Kind {
	case KindString:
		out += fmt.Sprintf("\nvoid lp_go_%s_free_str(char* p);", b.GoName)
	case KindBytes:
		out += fmt.Sprintf("\nvoid lp_go_%s_free_bytes(uint8_t* p);", b.GoName)
	}
	return out
}

func writeGoFunc(w *strings.Builder, b Binding) {
	args, _ := parseTypes(b.Args)
	result, _ := parseType(b.Result)
	names := make([]string, len(args))
	for i := range args {
		names[i] = fmt.Sprintf("a%d", i)
	}
	var sig []string
	for i, t := range args {
		sig = append(sig, fmt.Sprintf("%s %s", names[i], t.GoType(nil, b)))
	}
	ret := " " + result.GoType(nil, b)
	fmt.Fprintf(w, "func %s(%s)%s {\n", b.GoName, strings.Join(sig, ", "), ret)

	var call []string
	for i, t := range args {
		switch t.Kind {
		case KindBool:
			call = append(call, "b2u("+names[i]+")")
		case KindEnum:
			call = append(call, fmt.Sprintf("C.uint8_t(%s)", names[i]))
		case KindString:
			fmt.Fprintf(w, "\t%s := C.CString(%s)\n", "c"+names[i], names[i])
			fmt.Fprintf(w, "\tdefer C.free(unsafe.Pointer(%s))\n", "c"+names[i])
			call = append(call, "c"+names[i])
		case KindBytes:
			fmt.Fprintf(w, "\tvar %s *C.uint8_t\n", "p"+names[i])
			fmt.Fprintf(w, "\tif len(%s) > 0 {\n\t\t%s = (*C.uint8_t)(unsafe.Pointer(&%s[0]))\n\t}\n", names[i], "p"+names[i], names[i])
			call = append(call, "p"+names[i], "C.size_t(len("+names[i]+"))")
		default:
			call = append(call, fmt.Sprintf("C.%s(%s)", cgoTypeName(t), names[i]))
		}
	}

	switch result.Kind {
	case KindBytes:
		fmt.Fprintf(w, "\tvar %s *C.uint8_t\n", "outData")
		fmt.Fprintf(w, "\tvar %s C.size_t\n", "outLen")
		call = append(call, "&"+`outData`, "&"+`outLen`)
		fmt.Fprintf(w, "\tC.lp_go_%s(%s)\n", b.GoName, strings.Join(call, ", "))
		fmt.Fprintf(w, "\tdefer C.lp_go_%s_free_bytes(outData)\n", b.GoName)
		w.WriteString("\tout := make([]byte, int(outLen))\n")
		w.WriteString("\tcopy(out, unsafe.Slice((*byte)(unsafe.Pointer(outData)), int(outLen)))\n")
		w.WriteString("\treturn out\n")
	case KindString:
		fmt.Fprintf(w, "\tout := C.lp_go_%s(%s)\n", b.GoName, strings.Join(call, ", "))
		fmt.Fprintf(w, "\tdefer C.lp_go_%s_free_str(out)\n", b.GoName)
		w.WriteString("\treturn C.GoString(out)\n")
	case KindBool:
		fmt.Fprintf(w, "\treturn C.lp_go_%s(%s) != 0\n", b.GoName, strings.Join(call, ", "))
	case KindEnum:
		fmt.Fprintf(w, "\treturn %s(C.lp_go_%s(%s))\n", result.Enum, b.GoName, strings.Join(call, ", "))
	default:
		fmt.Fprintf(w, "\treturn %s(C.lp_go_%s(%s))\n", result.GoType(nil, b), b.GoName, strings.Join(call, ", "))
	}
	w.WriteString("}\n\n")
}

func cgoTypeName(t Type) string {
	switch t.Kind {
	case KindBool:
		return "uint8_t"
	case KindEnum:
		return "uint8_t"
	case KindScalar:
		switch t.Name {
		case "uint8":
			return "uint8_t"
		case "uint16":
			return "uint16_t"
		case "uint32":
			return "uint32_t"
		case "uint64":
			return "uint64_t"
		case "int8":
			return "int8_t"
		case "int16":
			return "int16_t"
		case "int32":
			return "int32_t"
		case "int64":
			return "int64_t"
		case "usize":
			return "size_t"
		case "float":
			return "double"
		case "float32":
			return "float"
		case "rune":
			return "uint32_t"
		}
	}
	return "void"
}

func writeGoFile(path, src string) error {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("formatting generated %s: %w", path, err)
	}
	return os.WriteFile(path, formatted, 0o644)
}
