func glueFor(b Binding, mode string, initSyms []string) (string, error) {
	args, err := parseTypes(b.Args)
	if err != nil {
		return "", err
	}
	var result Type
	if b.Result != "" {
		result, err = parseType(b.Result)
		if err != nil {
			return "", err
		}
	}
	if mode == "none" {
		for _, t := range append(append([]Type{}, args...), result) {
			if t.NeedsRuntime() {
				return "", fmt.Errorf("binding %s.%s needs runtime-linked mode for %s types (set runtime = \"linked\")", b.Package, b.GoName, typeName(t))
			}
		}
	}
	if result.Kind == KindBool || result.Kind == KindScalar || result.Kind == KindEnum {
		// supported
	} else if result.Kind != KindString && result.Kind != KindBytes {
		return "", fmt.Errorf("binding %s.%s: result type %s is not supported by the generator yet", b.Package, b.GoName, typeName(result))
	}

	var s strings.Builder
	s.WriteString("// Code generated by leanport. DO NOT EDIT.\n")
	if mode == "linked" {
		s.WriteString("#include <lean/lean.h>\n")
	}
	s.WriteString("#include <stdint.h>\n#include <stddef.h>\n#include <stdlib.h>\n#include <string.h>\n\n")

	if mode == "linked" {
		s.WriteString("extern void lean_initialize_runtime_module(void);\n")
		s.WriteString("extern void lean_io_mark_end_initialization(void);\n")
		s.WriteString("extern lean_object* initialize_Init(uint8_t);\n")
		for _, sym := range initSyms {
			fmt.Fprintf(&s, "extern lean_object* %s(uint8_t);\n", sym)
		}
		s.WriteString("\nstatic int lp_inited = 0;\n")
		s.WriteString("static void lp_init(void) {\n")
		s.WriteString("  if (lp_inited) return;\n  lp_inited = 1;\n")
		s.WriteString("  lean_initialize_runtime_module();\n")
		s.WriteString("  initialize_Init(1);\n")
		for _, sym := range initSyms {
			fmt.Fprintf(&s, "  %s(1);\n", sym)
		}
		s.WriteString("  lean_io_mark_end_initialization();\n}\n\n")
	}

	// Prototype of the Lean-generated export.
	fmt.Fprintf(&s, "extern %s %s(%s);\n\n", result.CType(), b.Export, cParamList(args))

	// Public wrapper.
	fmt.Fprintf(&s, "%s lp_go_%s(%s) {\n", publicCType(result), b.GoName, publicCParams(args, result))
	if mode == "linked" {
		s.WriteString("  lp_init();\n")
	}
	var callArgs []string
	for i, t := range args {
		name := fmt.Sprintf("a%d", i)
		switch t.Kind {
		case KindString:
			fmt.Fprintf(&s, "  lean_object* x%d = lean_mk_string(%s);\n", i, name)
			callArgs = append(callArgs, fmt.Sprintf("x%d", i))
		case KindBytes:
			fmt.Fprintf(&s, "  lean_object* x%d = lean_alloc_sarray(1, %s_len, %s_len);\n", i, name, name)
			fmt.Fprintf(&s, "  if (%s_len) memcpy(lean_sarray_cptr(x%d), %s, %s_len);\n", name, i, name, name)
			callArgs = append(callArgs, fmt.Sprintf("x%d", i))
		default:
			callArgs = append(callArgs, name)
		}
	}
	call := fmt.Sprintf("%s(%s)", b.Export, strings.Join(callArgs, ", "))

	switch {
	case result.Kind == KindString:
		fmt.Fprintf(&s, "  lean_object* r = %s;\n", call)
		s.WriteString("  char* out = strdup(lean_string_cstr(r));\n  lean_dec(r);\n  return out;\n")
		fmt.Fprintf(&s, "}\n\nvoid lp_go_%s_free_str(char* p) { free(p); }\n", b.GoName)
	case result.Kind == KindBytes:
		fmt.Fprintf(&s, "  lean_object* r = %s;\n", call)
		s.WriteString("  size_t n = lean_sarray_size(r);\n")
		s.WriteString("  uint8_t* out = (uint8_t*)malloc(n ? n : 1);\n")
		s.WriteString("  if (n) memcpy(out, lean_sarray_cptr(r), n);\n")
		s.WriteString("  lean_dec(r);\n  *out_data = out;\n  *out_len = n;\n")
		fmt.Fprintf(&s, "}\n\nvoid lp_go_%s_free_bytes(uint8_t* p) { free(p); }\n", b.GoName)
	default:
		fmt.Fprintf(&s, "  return %s;\n}\n", call)
	}

	if mode == "none" {
		s.WriteString(`
/* Fail-closed stubs for the runtime entry points that appear only in the
   generated module initializer's dead code path. Scalar exports never call
   them; aborting on the panic/assert paths is intentional.

   They are weak so several runtime-free archives can be linked into one Go
   binary. The linker keeps one definition instead of reporting duplicates. */
#if defined(__GNUC__) || defined(__clang__)
#define LP_WEAK __attribute__((weak))
#else
#define LP_WEAK
#endif
LP_WEAK void initialize_Init(uint8_t b) { (void)b; }
LP_WEAK void lean_inc_heartbeat(void) {}
LP_WEAK void* mi_malloc_small(size_t n) { (void)n; return 0; }
LP_WEAK void lean_dec_ref_cold(void* o) { (void)o; }
LP_WEAK void lean_internal_panic_out_of_memory(void) { abort(); }
LP_WEAK void lean_notify_assert(const char* f, int l, const char* c) { (void)f; (void)l; (void)c; abort(); }
`)
	}
	return s.String(), nil
}

func parseTypes(ss []string) ([]Type, error) {
	out := make([]Type, 0, len(ss))
	for _, s := range ss {
		t, err := parseType(s)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, nil
}

func typeName(t Type) string {
	switch t.Kind {
	case KindBool:
		return "bool"
	case KindScalar:
		return t.Name
	case KindEnum:
		return t.Enum
	case KindString:
		return "string"
	case KindBytes:
		return "bytes"
	}
	return "?"
}

// cParamList is the Lean export ABI: boxed values arrive as lean_object*.
func cParamList(args []Type) string {
	var parts []string
	for i, t := range args {
		parts = append(parts, fmt.Sprintf("%s a%d", t.CType(), i))
	}
	return strings.Join(parts, ", ")
}

func publicCType(result Type) string {
	switch result.Kind {
	case KindString:
		return "char*"
	case KindBytes:
		return "void"
	default:
		return result.CType()
	}
}

func publicCParams(args []Type, result Type) string {
	parts := []string{}
	for i, t := range args {
		switch t.Kind {
		case KindString:
			parts = append(parts, fmt.Sprintf("const char* a%d", i))
		case KindBytes:
			parts = append(parts, fmt.Sprintf("const uint8_t* a%d, size_t a%d_len", i, i))
		default:
			parts = append(parts, fmt.Sprintf("%s a%d", t.CType(), i))
		}
	}
	if result.Kind == KindBytes {
		parts = append(parts, "uint8_t** out_data", "size_t* out_len")
	}
	return strings.Join(parts, ", ")
}

