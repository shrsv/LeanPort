package app

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

func cmdDoctor(root string, args []string) error {
	fs := newFlags("doctor", os.Stderr)
	if done, err := parseFlags(fs, args); err != nil || done {
		return err
	}

	fmt.Println("LeanPort doctor")
	fmt.Println()
	missing := false
	probeDir := root
	if e, err := loadEnv(root); err == nil {
		// elan selects a toolchain by walking up from the working directory.
		// Probe from lean/ so it sees lean/lean-toolchain and does not try to
		// download the default toolchain.
		probeDir = e.leanDir()
	}
	check := func(label, bin string, required bool, versionArgs ...string) {
		path, err := exec.LookPath(bin)
		if err != nil {
			fmt.Printf("  %-10s MISSING\n", label)
			if required {
				missing = true
			}
			return
		}
		v := ""
		if len(versionArgs) > 0 {
			ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
			defer cancel()
			cmd := exec.CommandContext(ctx, bin, versionArgs...)
			cmd.Dir = probeDir
			out, err := cmd.Output()
			if err == nil {
				v = strings.TrimSpace(strings.SplitN(string(out), "\n", 2)[0])
			} else if ctx.Err() != nil {
				v = "(timed out)"
			}
		}
		fmt.Printf("  %-10s %s  %s\n", label, path, v)
	}
	check("go", "go", true, "version")
	check("cc", "cc", true, "--version")
	check("lean", "lean", true, "--version")
	check("lake", "lake", true, "--version")
	check("nix", "nix", false, "--version")

	fmt.Println()
	if os.Getenv("CGO_ENABLED") == "" || os.Getenv("CGO_ENABLED") == "1" {
		fmt.Println("  CGO_ENABLED  enabled")
	} else {
		fmt.Printf("  CGO_ENABLED  %s (bindings require cgo)\n", os.Getenv("CGO_ENABLED"))
		missing = true
	}

	if _, err := os.Stat(configPath(root)); err == nil {
		if e, err := loadEnv(root); err == nil {
			fmt.Println()
			fmt.Printf("  project      %s\n", e.cfg.Project.Name)
			fmt.Printf("  module       %s\n", e.cfg.Project.GoModule)
			fmt.Printf("  lean_dir     %s\n", e.leanDir())
			fmt.Printf("  targets      %s\n", strings.Join(e.cfg.Project.Targets, ", "))
			if p, err := e.leanPrefix(); err == nil {
				fmt.Printf("  lean prefix  %s\n", p)
			}
			if tc, err := os.ReadFile(filepath.Join(e.leanDir(), "lean-toolchain")); err == nil {
				fmt.Printf("  toolchain    %s\n", strings.TrimSpace(string(tc)))
			}
			fmt.Printf("  bindings     %d\n", len(e.cfg.Bindings))
		}
	} else {
		fmt.Println()
		fmt.Println("  no leanport.toml here (run leanport init)")
	}

	if missing {
		return fmt.Errorf("required tooling is missing")
	}
	fmt.Println("\n✓ toolchains look usable")
	return nil
}

func cmdDocs(root string, args []string) error {
	fs := newFlags("docs", os.Stderr)
	if done, err := parseFlags(fs, args); err != nil || done {
		return err
	}
	e, err := loadEnv(root)
	if err != nil {
		return err
	}

	byModule := map[string][]Binding{}
	var modules []string
	for _, b := range e.cfg.Bindings {
		if _, ok := byModule[b.Module]; !ok {
			modules = append(modules, b.Module)
		}
		byModule[b.Module] = append(byModule[b.Module], b)
	}

	for _, module := range modules {
		dir := filepath.Join(e.leanDir(), "LeanPort", module)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		var rows strings.Builder
		for _, b := range byModule[module] {
			fmt.Fprintf(&rows, "| `%s` | `%s.%s` | `%s` | `%s` |\n", b.Export, b.Package, b.GoName, strings.Join(b.Args, ", "), b.Result)
		}
		content := fmt.Sprintf(`# %s specification

> Generated by `+"`leanport docs`"+`. Edit `+"`Policy.lean`"+` and `+"`Proofs.lean`"+`,
> not this file.

## Exports

| C symbol | Go | Arguments | Result |
|---|---|---|---|
%s
## Guarantees

See `+"`Proofs.lean`"+` for the machine-checked theorems.
`, module, rows.String())
		if err := os.WriteFile(filepath.Join(dir, "SPEC.md"), []byte(content), 0o644); err != nil {
			return err
		}
		fmt.Printf("wrote %s/SPEC.md\n", dir)
	}
	return nil
}
